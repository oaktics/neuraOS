import {bundleRustLicenses} from './rust-licenses.mjs';
import {signApplication,selectIdentity} from '../signing/sign.mjs';
import {packageNativeRuntime} from './native-runtime.mjs';
import {resolve,join} from 'node:path';
import {execFileSync} from 'node:child_process';
const root=resolve(import.meta.dirname,'../../..');
const app=resolve(process.env.NEURA_APP_OUTPUT??join(root,'apps/macos/dist/neuraOS.app'));
await bundleRustLicenses(root,app);
await packageNativeRuntime(app,join(root,'crates/native-core/target/release/neura-native-core'),join(root,'apps/macos/.build/release/NeuraUpdater'));
signApplication(app,selectIdentity());
execFileSync('codesign',['--verify','--deep','--strict',app],{stdio:'inherit'});
console.log(app);
